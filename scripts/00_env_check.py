# pandas 라이브러리를 pd라는 이름으로 불러온다
import pandas as pd

# 누가 봐도 가짜인 도서명 3개와 숫자 가격으로 표를 만든다
df = pd.DataFrame({
    # 도서명 열: 가짜 이름 3개
    "도서명": ["가짜문제집A", "가짜문제집B", "가짜문제집C"],
    # 판매가 열: 숫자로 된 가격 3개
    "판매가": [10000, 12000, 15000],
})

# 표 위에 안내 문구를 출력한다
print("환경 확인용 가상 예시")
# 표를 출력한다
print(df)
# 표의 크기(행 수, 열 수)를 출력한다
print(df.shape)
